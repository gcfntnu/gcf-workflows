"""Fill a public dataset into EXT_DIR: download its runs and composition table once, checked against recorded checksums.

A pool declaration names a data folder relative to EXT_DIR (`data`), the composition table (`composition`: file, url,
sha256) and the runs (`runs`: run, url, md5, ...). Files go to `<EXT_DIR>/<data>/`: runs as `fastq/<run>.fastq.gz`,
the table as `composition/<file>`, the miRBase mature sequences (`mirbase`: release, url, sha256) as
`mirbase/<release>/mature.fa`. Each file is written under a temporary name in the same folder and renamed only after
its checksum matches, so a file in place is always complete; files already in place are skipped. Several
declarations may share a data folder. This is the only step of the benchmark that writes to EXT_DIR, and it is run
deliberately when a dataset is added; `prepare` and `evaluate` only read.
"""
import hashlib
import os
from pathlib import Path
import shutil
import urllib.request

CHUNK = 1 << 20


def targets(spec, ext_dir):
    """[(url, algorithm, digest, final path)] for every file of a pool declaration."""
    data = Path(ext_dir) / spec['data']
    comp = spec['composition']
    mirbase = spec['mirbase']
    files = [(comp['url'], 'sha256', comp['sha256'], data / 'composition' / comp['file']),
             (mirbase['url'], 'sha256', mirbase['sha256'], data / 'mirbase' / str(mirbase['release']) / 'mature.fa')]
    files += [(run['url'], 'md5', run['md5'], data / 'fastq' / '{}.fastq.gz'.format(run['run'])) for run in spec['runs']]
    return files


def download(url, algorithm, digest, path, log=print):
    """Download url to path through a temporary file; fail (and remove it) when the checksum differs."""
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name('.partial-' + path.name)
    checksum = hashlib.new(algorithm)
    try:
        with urllib.request.urlopen(url, timeout=600) as response, open(partial, 'wb') as out:
            for block in iter(lambda: response.read(CHUNK), b''):
                checksum.update(block)
                out.write(block)
        if checksum.hexdigest() != digest:
            raise ValueError('{}: {} {} does not match the declared {}'.format(url, algorithm, checksum.hexdigest(), digest))
        os.replace(partial, path)
    finally:
        if partial.exists():
            partial.unlink()
    log('{}: {} checked'.format(path, algorithm))


def fill(spec, ext_dir, log=print, fetch=download):
    """Download the declaration's missing files into EXT_DIR. Returns the number of files downloaded."""
    if spec.get('kind') != 'pool':
        raise ValueError('{}: only pool datasets are filled; synthetic datasets are generated by prepare'.format(spec['name']))
    done = 0
    for url, algorithm, digest, path in targets(spec, ext_dir):
        if path.exists():
            log('{}: in place'.format(path))
            continue
        fetch(url, algorithm, digest, path, log)
        done += 1
    free = shutil.disk_usage(Path(ext_dir) / spec['data']).free
    log('{}: {} file(s) downloaded, {:.0f} GB free'.format(spec['name'], done, free / 1e9))
    return done
